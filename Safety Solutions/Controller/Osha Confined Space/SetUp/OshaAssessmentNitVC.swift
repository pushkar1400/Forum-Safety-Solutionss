        if btnRespirator.isSelected == true{
            imgRespirator.image = UIImage(named: "checkBox")
            Respirator = true
            self.validation127 = true
            UserDefaults.standard.set(self.validation127, forKey: "val127")
        }else if !btnRespirator.isSelected == true{
            imgRespirator.image = UIImage(named: "ic_uncheck")
            Respirator = false
            UserDefaults.standard.set(false, forKey: "val127")
        }
    }
